-- AGREGAÇÃO — DESAFIO: CLIENTE, PEDIDO E ITEM_PEDIDO

CREATE TABLE cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_pedido TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_cliente BIGINT NOT NULL,
    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
        ON DELETE RESTRICT,
    CONSTRAINT uk_pedido_cliente_data UNIQUE (id_cliente, data_pedido)
);

CREATE TABLE agg_item_pedido (
    id_pedido BIGINT NOT NULL,
    id_produto BIGINT NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0),
    CONSTRAINT pk_agg_item_pedido PRIMARY KEY (id_pedido, id_produto),
    CONSTRAINT fk_agg_item_pedido_pedido
        FOREIGN KEY (id_pedido) REFERENCES agg_pedido(id_pedido)
        ON DELETE CASCADE,
    CONSTRAINT fk_agg_item_pedido_produto
        FOREIGN KEY (id_produto) REFERENCES agg_produto(id_produto)
        ON DELETE RESTRICT
);

