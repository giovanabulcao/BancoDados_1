-- a) Total de pedidos por cliente, incluindo clientes sem pedidos.
SELECT
    c.nome AS cliente,
    COUNT(pe.id_pedido) AS total_pedidos
FROM cliente AS c
LEFT JOIN agg_pedido AS pe ON pe.id_cliente = c.id_cliente
GROUP BY c.id_cliente, c.nome
ORDER BY c.nome;

-- b) Valor total de cada pedido.
SELECT
    pe.id_pedido,
    pe.data_pedido,
    SUM(ip.quantidade * ip.preco_unitario) AS valor_total_pedido
FROM pedido AS pe
INNER JOIN agg_item_pedido AS ip ON ip.id_pedido = pe.id_pedido
GROUP BY pe.id_pedido, pe.data_pedido
ORDER BY pe.data_pedido;

-- c) Total gasto por cliente, incluindo clientes que nunca fizeram pedidos.
SELECT
    c.nome AS cliente,
    COALESCE(SUM(ip.quantidade * ip.preco_unitario), 0) AS total_gasto
FROM cliente AS c
LEFT JOIN pedido AS pe ON pe.id_cliente = c.id_cliente
LEFT JOIN agg_item_pedido AS ip ON ip.id_pedido = pe.id_pedido
GROUP BY c.id_cliente, c.nome
ORDER BY c.nome;

-- d) Ticket médio por cliente: média dos valores totais de seus pedidos.
-- A subconsulta calcula primeiro o total de cada pedido.
SELECT
    c.nome AS cliente,
    COALESCE(AVG(totais.valor_pedido), 0) AS ticket_medio
FROM cliente AS c
LEFT JOIN pedido AS pe ON pe.id_cliente = c.id_cliente
LEFT JOIN (
    SELECT id_pedido, SUM(quantidade * preco_unitario) AS valor_pedido
    FROM agg_item_pedido
    GROUP BY id_pedido
) AS totais ON totais.id_pedido = pe.id_pedido
GROUP BY c.id_cliente, c.nome
ORDER BY c.nome;

-- e) Clientes com total gasto acima de R$ 1.000.
SELECT
    c.nome AS cliente,
    SUM(ip.quantidade * ip.preco_unitario) AS total_gasto
FROM cliente AS c
INNER JOIN pedido AS pe ON pe.id_cliente = c.id_cliente
INNER JOIN agg_item_pedido AS ip ON ip.id_pedido = pe.id_pedido
GROUP BY c.id_cliente, c.nome
HAVING SUM(ip.quantidade * ip.preco_unitario) > 1000
ORDER BY total_gasto DESC;

-- f) Produto mais vendido por quantidade, preservando empates.
-- A subconsulta encontra a maior soma; a consulta externa retorna todo produto
-- cuja quantidade vendida seja igual a esse máximo.
SELECT
    pr.id_produto,
    pr.nome AS prod,
    SUM(ip.quantidade) AS quantidade_vendida
FROM produto AS pr
INNER JOIN agg_item_pedido AS ip ON ip.id_produto = pr.id_produto
GROUP BY pr.id_produto, pr.nome
HAVING SUM(ip.quantidade) = (
    SELECT MAX(vendas.quantidade_total)
    FROM (
        SELECT SUM(quantidade) AS quantidade_total
        FROM agg_item_pedido
        GROUP BY id_produto
    ) AS vendas
)
ORDER BY pr.nome;
