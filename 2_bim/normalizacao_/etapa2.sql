/* EXERCÍCIO 5

A coluna telefones armazena mais de um valor na mesma célula. Para permitir
consultar, cadastrar e excluir um telefone individualmente, separe os dados:
CLIENTE(id_cliente PK, nome_cliente)
TELEFONE(id_telefone PK, numero, id_cliente FK)
Cardinalidade: CLIENTE 1:N TELEFONE. Cada telefone pertence a um cliente;
um cliente pode ter vários telefones.
*/

CREATE TABLE cliente (
    id_cliente BIGINT PRIMARY KEY,
    nome_cliente VARCHAR(100) NOT NULL
);

CREATE TABLE telefone (
    id_telefone BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20) NOT NULL,
    id_cliente BIGINT NOT NULL,
    CONSTRAINT fk_telefone_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente(id_cliente)
        ON DELETE CASCADE,
    CONSTRAINT uk_cliente_numero UNIQUE (id_cliente, numero)
);

-- h), i), j) Crie as tabelas e insira os clientes e telefones apresentados.
INSERT INTO cliente (id_cliente, nome_cliente)
VALUES (1, 'Ana'), (2, 'Bruno'), (3, 'Carlos')
ON CONFLICT (id_cliente) DO NOTHING;

INSERT INTO telefone (numero, id_cliente)
VALUES
    ('9999-1111', 1),
    ('9888-2222', 1),
    ('9777-3333', 2),
    ('9666-4444', 3),
    ('9555-5555', 3),
    ('9444-6666', 3)
ON CONFLICT (id_cliente, numero) DO NOTHING;

-- k) Consulte todos os clientes
SELECT * FROM cliente ORDER BY id_cliente;

-- l) Consulte todos os telefones do cliente de identificador 1.
SELECT id_telefone, numero
FROM telefone
WHERE id_cliente = 1
ORDER BY numero;

-- m) Cadastre um novo telefone para o cliente de identificador 2
INSERT INTO telefone (numero, id_cliente)
VALUES ('9666-7777', 2)
ON CONFLICT (id_cliente, numero) DO NOTHING;

-- n) Exclua apenas um telefone do cliente 3, preservando os demais.
DELETE FROM telefone
WHERE id_cliente = 3
  AND numero = '9555-5555';

/* EXERCÍCIO 6 

As colunas disciplina_1, disciplina_2 e disciplina_3 limitam artificialmente
quantas disciplinas podem ser registradas e criam colunas repetidas. Se um
aluno cursar cinco disciplinas, a tabela precisaria ser alterada. O modelo
correto é N:N: ALUNO, DISCIPLINA e MATRICULA (tabela associativa).
*/

CREATE TABLE aluno (
    id_aluno BIGINT PRIMARY KEY,
    nome_aluno VARCHAR(100) NOT NULL
);

CREATE TABLE disciplina (
    id_disciplina BIGINT PRIMARY KEY,
    nome_disciplina VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE matricula (
    id_aluno BIGINT NOT NULL,
    id_disciplina BIGINT NOT NULL,
    CONSTRAINT pk_matricula PRIMARY KEY (id_aluno, id_disciplina),
    CONSTRAINT fk_matricula_aluno
        FOREIGN KEY (id_aluno) REFERENCES aluno(id_aluno),
    CONSTRAINT fk_matricula_disciplina
        FOREIGN KEY (id_disciplina) REFERENCES disciplina(id_disciplina)
);

