/* EXERCÍCIO 2 

Exemplos de anomalias:
- Inserção: não é possível cadastrar um departamento sem funcionário.
- Atualização: alterar gerente_departamento exige mudar todas as linhas dos
  funcionários do departamento; uma atualização incompleta gera inconsistência.
- Exclusão: excluir o último funcionário pode remover também os dados do departamento.

Atributos de FUNCIONARIO: id_funcionario, nome_funcionario, salario, id_departamento.
Atributos de DEPARTAMENTO: id_departamento, nome_departamento, gerente_departamento.
Regra: id_departamento -> nome_departamento, gerente_departamento.
Modelo proposto: DEPARTAMENTO(id_departamento PK, nome_departamento, gerente_departamento)
 e FUNCIONARIO(id_funcionario PK, nome_funcionario, salario, id_departamento FK).
*/

-- Implementação da estrutura proposta no exercício 2.
CREATE TABLE IF NOT EXISTS norm_ex02_departamento (
    id_departamento BIGINT PRIMARY KEY,
    nome_departamento VARCHAR(100) NOT NULL,
    gerente_departamento VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS norm_ex02_funcionario (
    id_funcionario BIGINT PRIMARY KEY,
    nome_funcionario VARCHAR(100) NOT NULL,
    salario NUMERIC(10,2) NOT NULL CHECK (salario >= 0),
    id_departamento BIGINT NOT NULL,
    CONSTRAINT fk_norm_ex02_funcionario_departamento
        FOREIGN KEY (id_departamento)
        REFERENCES norm_ex02_departamento(id_departamento)
);

/* EXERCÍCIO 3 

Chave primária: id_produto.
Dependências funcionais:
- id_produto -> nome_produto, preco, id_categoria.
- id_categoria -> nome_categoria.
- Portanto, id_produto -> nome_categoria de forma transitiva, passando por
  id_categoria.

id_produto determina o id_categoria, mas o id_categoria é que determina
 diretamente o nome da categoria. Uma categoria pode ter vários produtos,
 então id_categoria não determina um nome_produto único.
A relação apresenta dependência transitiva e deve ser separada em CATEGORIA
(id_categoria PK, nome_categoria) e PRODUTO(id_produto PK, nome_produto,
preco, id_categoria FK).
*/

/* EXERCÍCIO 4 

Chaves candidatas: id_aluno e cpf, pois ambos identificam cada aluno de forma
única. Escolha de chave primária: id_aluno. cpf será uma chave alternativa,
implementada com NOT NULL e UNIQUE.
Atributos primos: id_aluno e cpf (participam de pelo menos uma chave candidata).
Atributos não primos: nome e email. Um atributo pode ser primo sem ser a chave
primária porque pode pertencer a outra chave candidata, como cpf neste caso.
*/

CREATE TABLE IF NOT EXISTS norm_ex04_aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf CHAR(11) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150)
);

