-- a) Mostre os pedidos com seus clientes.
SELECT
    p.id_pedido,
    p.data_pedido,
    c.nome AS cliente,
    p.valor
FROM pedido AS p
INNER JOIN cliente AS c
    ON p.id_cliente = c.id_cliente
ORDER BY p.id_pedido;

-- b) Mostre todos os clientes, inclusive os sem pedidos.
SELECT
    c.id_cliente,
    c.nome AS cliente,
    p.id_pedido,
    p.data_pedido,
    p.valor
FROM cliente AS c
LEFT JOIN pedido AS p
    ON c.id_cliente = p.id_cliente
ORDER BY c.nome, p.data_pedido;

-- c) Mostre apenas clientes sem pedidos.
SELECT
    c.id_cliente,
    c.nome AS cliente
FROM cliente AS c
LEFT JOIN pedido AS p
    ON c.id_cliente = p.id_cliente
WHERE p.id_pedido IS NULL
ORDER BY c.nome;

-- d) Ordene os pedidos por data.
SELECT id_pedido, data_pedido, valor, id_cliente
FROM pedido
ORDER BY data_pedido ASC;

